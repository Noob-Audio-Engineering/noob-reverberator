//! Regenerates `docs/BENCHMARK.md`.
//!
//! Every row here is measured from **rendered audio**: an impulse is run
//! through the engine, the tail is filtered into octave bands, and the decay
//! is read out of each band by integrating the energy backwards. Nothing asks
//! the filters what they intended.
//!
//! ```text
//! cargo run --release --bin benchmark
//! ```

use std::fmt::Write as _;

use noob_reverberator::dsp::colour::Era;
