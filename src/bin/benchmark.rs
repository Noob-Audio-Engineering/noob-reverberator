use noob_reverberator::dsp::mode::MODES;
use noob_reverberator::dsp::shape::Kind as ShapeKind;

const FS: f32 = 48_000.0;

/// A settings block with everything quiet, to be written over per case.
fn plain(decay: f32) -> Settings {
    Settings {
        bypass: false,
        mix: 1.0,
        output: 1.0,
        freeze: false,
        mode: 0,
        decay,
        size: 1.0,
        density: 0.8,
        attack_ms: 0.0,
        predelay_ms: 0.0,
        predelay_sync: 0,
        predelay_offset: 1.0,
        tempo: None,
        width: 1.0,
        mod_rate: 0.0,
        mod_depth: 0.0,
        mod_random: 0.0,
        mod_chaos: 0.0,
        early_level: 0.0,
        early_size: 8.0,
        early_absorb: 0.35,
        early_taps: 24,
        shift: 0.0,
        shift_mix: 0.0,
        shift_window: 16_384.0,
        shape: ShapeKind::Off,
        shape_hold: 400.0,
        era: Era::Now,
        era_amount: 0.0,
        tension: 0.6,
        sections: 100,
        lines: 12,
        distance: 0.0,
        thickness: 0.0,
        duck: 0.0,
        duck_release: 250.0,
        gate: 0.0,
        gate_hold: 300.0,
        bloom: 0.0,
        bloom_time: 120.0,
        bloom_swell: 600.0,
        tape_mix: 0.0,
        tape_time: 320.0,
        tape_heads: 3,
        tape_feedback: 0.35,
        tape_wobble: 0.3,
        tape_drive: 0.3,
        choir_amount: 0.0,
        choir_vowel: 0.0,
        choir_spread: 0.0,
        choir_resonance: 0.5,
        curve: Curve {
            base: decay,
            ..Default::default()
        },
    }
}

/// Render an impulse response of `secs` seconds.
fn render(s: &Settings, secs: f32) -> Vec<f32> {
    let mut rev = Reverb::new(FS);
    rev.configure(s);
    let n = (FS * secs) as usize;
    let mut l = vec![0.0f32; n];
    let mut r = vec![0.0f32; n];
    l[0] = 1.0;
    r[0] = 1.0;
    rev.process(s, &mut l, &mut r);
    l.iter().zip(r.iter()).map(|(a, b)| 0.5 * (a + b)).collect()
}

/// One case: what was drawn, and what came out, per octave.
fn measure(s: &Settings, secs: f32, bands: &[f32]) -> Vec<(f32, f32, Option<f32>)> {
    let ir = render(s, secs);
    bands
        .iter()
        .map(|&f| (f, s.curve.t60_over_octave(f), t60_in_band(&ir, FS, f)))
        .collect()
}

fn worst(rows: &[(f32, f32, Option<f32>)]) -> Option<(f32, f32)> {
    let mut w = 0.0f32;
    let mut at = 0.0f32;
    for &(f, want, got) in rows {
        let got = got?;
        let e = (got / want).log2().abs();
        if e > w {
            w = e;
            at = f;
        }
    }
    Some((w, at))
}

